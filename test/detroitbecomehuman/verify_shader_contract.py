import argparse
import json
import re
import subprocess
import sys
from pathlib import Path


DESCRIPTOR_KINDS = (
    "ubos",
    "ssbos",
    "textures",
    "separate_images",
    "separate_samplers",
    "images",
    "subpass_inputs",
    "acceleration_structures",
)
CRC_PATTERN = re.compile(r"0x[0-9A-F]{8}")


def fail(message):
    raise AssertionError(message)


def run_checked(command, description):
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        details = (result.stdout + result.stderr).strip()
        fail(f"{description} failed ({result.returncode}): {details}")
    return result.stdout


def normalize_io(reflection, key):
    return sorted(
        ({"location": item["location"], "type": item["type"]}
         for item in reflection.get(key, [])),
        key=lambda item: (item["location"], item["type"]),
    )


def normalize_descriptors(reflection):
    descriptors = []
    for kind in DESCRIPTOR_KINDS:
        for resource in reflection.get(kind, []):
            descriptor = {
                "kind": kind,
                "set": resource["set"],
                "binding": resource["binding"],
            }
            if kind not in ("ubos", "ssbos"):
                descriptor["type"] = resource["type"]
            for attribute in ("block_size", "format", "readonly", "writeonly"):
                if attribute in resource:
                    descriptor[attribute] = resource[attribute]
            descriptors.append(descriptor)
    return sorted(
        descriptors,
        key=lambda item: (item["set"], item["binding"], item["kind"]),
    )


def validate_push_constant(shader_id, reflection, expected):
    push_constants = reflection.get("push_constants", [])
    if len(push_constants) != 1:
        fail(f"{shader_id}: expected one push-constant block, got {len(push_constants)}")

    types = reflection.get("types", {})
    outer = types.get(push_constants[0].get("type"))
    if outer is None:
        fail(f"{shader_id}: reflected push-constant type is missing")
    outer_members = outer.get("members", [])
    if len(outer_members) != 1 or outer_members[0].get("offset") != 0:
        fail(f"{shader_id}: injected data must be the sole push member at offset 0")

    injected = types.get(outer_members[0].get("type"))
    if injected is None or injected.get("name") != expected["block_name"]:
        fail(f"{shader_id}: ShaderInjectData reflection block is missing")

    members = [
        {"name": item["name"], "type": item["type"], "offset": item["offset"]}
        for item in injected.get("members", [])
    ]
    if members != expected["members"]:
        fail(f"{shader_id}: injected push-constant members or offsets changed")

    reflected_size = max(item["offset"] + 4 for item in members)
    if reflected_size != expected["size"]:
        fail(
            f"{shader_id}: expected {expected['size']}-byte push constants, "
            f"got {reflected_size}"
        )


def validate_no_push_constants(shader_id, reflection):
    push_constants = reflection.get("push_constants", [])
    if push_constants:
        fail(f"{shader_id}: expected no push constants, got {len(push_constants)}")


def validate_embed_header(shader_id, spv_path):
    header_path = spv_path.with_suffix(".h")
    if not header_path.is_file():
        fail(f"{shader_id}: generated embed header is missing")

    text = header_path.read_text(encoding="utf-8")
    array_match = re.search(
        rf"inline constexpr std::uint8_t __{re.escape(shader_id)}_base\[\] = \{{(.*?)\}};",
        text,
        flags=re.DOTALL,
    )
    if array_match is None:
        fail(f"{shader_id}: generated byte array was not found in embed header")
    embedded = bytes(int(value) for value in re.findall(r"\b\d+\b", array_match.group(1)))
    if embedded != spv_path.read_bytes():
        fail(f"{shader_id}: embed header bytes differ from generated SPIR-V")
    if f"std::span<const std::uint8_t> __{shader_id}" not in text:
        fail(f"{shader_id}: generated embed span registration is missing")


def validate_shader(shader_id, expected, push_expected, embed_dir, spirv_val, spirv_cross):
    spv_path = embed_dir / f"{shader_id}.spv"
    run_checked(
        [str(spirv_val), "--target-env", "vulkan1.3", str(spv_path)],
        f"{shader_id} spirv-val",
    )
    reflection = json.loads(
        run_checked([str(spirv_cross), str(spv_path), "--reflect"], f"{shader_id} reflection")
    )

    entry_points = reflection.get("entryPoints", [])
    if len(entry_points) != 1:
        fail(f"{shader_id}: expected one entry point, got {len(entry_points)}")
    entry = entry_points[0]
    if entry.get("name") != expected["entry_point"] or entry.get("mode") != expected["stage"]:
        fail(f"{shader_id}: stage or entry point changed: {entry}")
    if entry.get("workgroup_size") != expected.get("workgroup_size"):
        fail(f"{shader_id}: compute workgroup size changed")

    if normalize_io(reflection, "inputs") != expected["inputs"]:
        fail(f"{shader_id}: input locations or types changed")
    if normalize_io(reflection, "outputs") != expected["outputs"]:
        fail(f"{shader_id}: output locations or types changed")

    expected_descriptors = sorted(
        expected["descriptors"],
        key=lambda item: (item["set"], item["binding"], item["kind"]),
    )
    if normalize_descriptors(reflection) != expected_descriptors:
        fail(
            f"{shader_id}: descriptor interface changed\n"
            f"expected: {expected_descriptors}\n"
            f"actual:   {normalize_descriptors(reflection)}"
        )

    if expected.get("injected_push_constant", True):
        validate_push_constant(shader_id, reflection, push_expected)
    else:
        validate_no_push_constants(shader_id, reflection)
    validate_embed_header(shader_id, spv_path)


def validate_registry(embed_dir, shader_ids):
    shaders_header = embed_dir / "shaders.h"
    if not shaders_header.is_file():
        fail("generated shaders.h is missing")
    text = shaders_header.read_text(encoding="utf-8")
    includes = re.findall(r'#include "\./(0x[0-9A-F]{8})\.h"', text)
    registrations = re.findall(r"CustomShaderEntry\((0x[0-9A-F]{8})\)", text)
    if len(includes) != len(shader_ids) or set(includes) != shader_ids:
        fail(f"shaders.h includes do not match expected CRC shaders: {includes}")
    if len(registrations) != len(shader_ids) or set(registrations) != shader_ids:
        fail(f"shaders.h registrations do not match expected CRC shaders: {registrations}")

    if '#include "./temporal_aux.h"' not in text:
        fail("optimized temporal auxiliary shader is missing from shaders.h")
    for shader_id in ("retinal_horizontal", "retinal_vertical"):
        if f'#include "./{shader_id}.h"' not in text:
            fail(f"{shader_id} is missing from shaders.h")


def validate_temporal_auxiliary(
    embed_dir, spirv_val, spirv_cross, push_expected
):
    shader_id = "temporal_aux"
    spv_path = embed_dir / f"{shader_id}.spv"
    if not spv_path.is_file() or spv_path.stat().st_size > 60_000:
        fail("temporal_aux debug-capable SPIR-V is missing or unexpectedly large")
    run_checked(
        [str(spirv_val), "--target-env", "vulkan1.3", str(spv_path)],
        "temporal_aux spirv-val",
    )
    reflection = json.loads(
        run_checked(
            [str(spirv_cross), str(spv_path), "--reflect"],
            "temporal_aux reflection",
        )
    )
    entry_points = reflection.get("entryPoints", [])
    if len(entry_points) != 1 or entry_points[0].get("mode") != "comp":
        fail("temporal_aux is not a single compute entry point")
    if entry_points[0].get("workgroup_size") != [8, 8, 1]:
        fail("temporal_aux workgroup size changed")
    descriptors = normalize_descriptors(reflection)
    expected_bindings = {
        ("textures", 0),
        ("textures", 1),
        ("textures", 2),
        ("textures", 3),
        ("textures", 4),
        ("textures", 5),
        ("textures", 6),
        ("textures", 7),
        ("images", 16),
        ("images", 17),
        ("images", 18),
        ("images", 19),
        ("ubos", 52),
    }
    actual_bindings = {(item["kind"], item["binding"]) for item in descriptors}
    if actual_bindings != expected_bindings:
        fail(
            "temporal_aux must retain native TAA debug and history bindings; "
            f"got {sorted(actual_bindings)}"
        )
    validate_push_constant(shader_id, reflection, push_expected)
    validate_embed_header(shader_id, spv_path)


def validate_dlaa_pack_shader(embed_dir, spirv_val, spirv_cross):
    shader_id = "detroit_dlss_pack_color"
    spv_path = embed_dir / f"{shader_id}.spv"
    if not spv_path.is_file():
        fail("DLAA output pack SPIR-V is missing")
    run_checked(
        [str(spirv_val), "--target-env", "vulkan1.3", str(spv_path)],
        "DLAA pack spirv-val",
    )
    reflection = json.loads(
        run_checked(
            [str(spirv_cross), str(spv_path), "--reflect"],
            "DLAA pack reflection",
        )
    )
    entry_points = reflection.get("entryPoints", [])
    if len(entry_points) != 1 or entry_points[0].get("mode") != "comp":
        fail("DLAA output pack is not a single compute entry point")
    if entry_points[0].get("workgroup_size") != [8, 8, 1]:
        fail("DLAA output pack workgroup size changed")
    descriptors = normalize_descriptors(reflection)
    actual_bindings = {
        (item["kind"], item["set"], item["binding"])
        for item in descriptors
    }
    expected_bindings = {
        ("textures", 0, 0),
        ("images", 0, 1),
        ("ubos", 0, 2),
    }
    if actual_bindings != expected_bindings:
        fail(
            "DLAA output pack must sample NGX color, write native b16 and "
            f"read bundle-local sharpening constants; got {sorted(actual_bindings)}"
        )
    uniform = reflection.get("ubos", [])
    if len(uniform) != 1 or uniform[0].get("block_size") != 16:
        fail("DLAA output pack constants block must remain 16 bytes")
    validate_no_push_constants(shader_id, reflection)
    validate_embed_header(shader_id, spv_path)


def validate_retinal_shader(shader_id, embed_dir, spirv_val, spirv_cross):
    spv_path = embed_dir / f"{shader_id}.spv"
    if not spv_path.is_file():
        fail(f"{shader_id}: SPIR-V is missing")
    run_checked(
        [str(spirv_val), "--target-env", "vulkan1.3", str(spv_path)],
        f"{shader_id} spirv-val",
    )
    reflection = json.loads(
        run_checked(
            [str(spirv_cross), str(spv_path), "--reflect"],
            f"{shader_id} reflection",
        )
    )
    entry_points = reflection.get("entryPoints", [])
    if (
        len(entry_points) != 1
        or entry_points[0].get("name") != "main"
        or entry_points[0].get("mode") != "comp"
    ):
        fail(f"{shader_id}: expected one compute entry point")
    if entry_points[0].get("workgroup_size") != [8, 8, 1]:
        fail(f"{shader_id}: workgroup size changed")
    if reflection.get("inputs", []) or reflection.get("outputs", []):
        fail(f"{shader_id}: unexpected stage inputs or outputs")

    expected_descriptors = [
        {
            "kind": "separate_samplers",
            "set": 0,
            "binding": 0,
            "type": "sampler",
        },
        {
            "kind": "separate_images",
            "set": 0,
            "binding": 1,
            "type": "texture2D",
        },
        {
            "kind": "images",
            "set": 0,
            "binding": 2,
            "type": "image2D",
            "format": "rgba16f",
            "writeonly": True,
        },
    ]
    descriptors = normalize_descriptors(reflection)
    if descriptors != expected_descriptors:
        fail(
            f"{shader_id}: descriptor interface changed; "
            f"got {descriptors}"
        )
    output_images = reflection.get("images", [])
    if (
        len(output_images) != 1
        or output_images[0].get("format") != "rgba16f"
        or not output_images[0].get("writeonly")
    ):
        fail(f"{shader_id}: output must remain a write-only rgba16f image")

    push_constants = reflection.get("push_constants", [])
    if len(push_constants) != 1:
        fail(f"{shader_id}: expected one push-constant block")
    push_type = reflection.get("types", {}).get(push_constants[0].get("type"))
    if push_type is None:
        fail(f"{shader_id}: reflected push-constant type is missing")
    members = push_type.get("members", [])
    expected_members = [
        ("fixationUv", "vec2", 0),
        ("inverseOutputSize", "vec2", 8),
        ("outputSize", "vec2", 16),
        ("tanHalfHorizontal", "float", 24),
        ("tanHalfVertical", "float", 28),
        ("horizontalPixelsPerDegree", "float", 32),
        ("verticalPixelsPerDegree", "float", 36),
        ("fixationBlend", "float", 40),
        ("maximumSigmaPixels", "float", 44),
        ("highQuality", "float", 48),
    ]
    actual_members = [
        (member.get("name"), member.get("type"), member.get("offset"))
        for member in members
    ]
    if actual_members != expected_members:
        fail(f"{shader_id}: push-constant member contract changed")
    reflected_size = max(
        member["offset"] + (8 if member["type"] == "vec2" else 4)
        for member in members
    )
    if reflected_size != 52:
        fail(f"{shader_id}: expected 52-byte push constants, got {reflected_size}")
    validate_embed_header(shader_id, spv_path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", required=True, type=Path)
    parser.add_argument("--embed-dir", required=True, type=Path)
    parser.add_argument("--expected", required=True, type=Path)
    parser.add_argument("--spirv-val", required=True, type=Path)
    parser.add_argument("--spirv-cross", required=True, type=Path)
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    embed_dir = args.embed_dir.resolve()
    if not embed_dir.is_dir():
        fail(f"generated shader directory does not exist: {embed_dir}")

    tools = (args.spirv_val.resolve(), args.spirv_cross.resolve())
    for tool in tools:
        if not tool.is_file() or repo_root not in tool.parents:
            fail(f"shader contract requires a repo-local tool: {tool}")

    fixture = json.loads(args.expected.read_text(encoding="utf-8"))
    shaders = fixture["shaders"]
    shader_ids = set(shaders)
    if any(CRC_PATTERN.fullmatch(shader_id) is None for shader_id in shader_ids):
        fail("fixture contains a non-CRC32 shader filename")

    generated_spv = {path.stem for path in embed_dir.glob("0x*.spv")}
    generated_headers = {path.stem for path in embed_dir.glob("0x*.h")}
    if generated_spv != shader_ids:
        fail(f"generated SPIR-V CRC set changed: {sorted(generated_spv)}")
    if generated_headers != shader_ids:
        fail(f"generated embed-header CRC set changed: {sorted(generated_headers)}")

    for shader_id in sorted(shader_ids):
        validate_shader(
            shader_id,
            shaders[shader_id],
            fixture["push_constant"],
            embed_dir,
            tools[0],
            tools[1],
        )
    validate_registry(embed_dir, shader_ids)
    validate_temporal_auxiliary(
        embed_dir, tools[0], tools[1], fixture["push_constant"]
    )
    validate_dlaa_pack_shader(embed_dir, tools[0], tools[1])
    for shader_id in ("retinal_horizontal", "retinal_vertical"):
        validate_retinal_shader(shader_id, embed_dir, tools[0], tools[1])

    print(
        f"PASS: validated {len(shader_ids)} Detroit production SPIR-V shader "
        "contracts plus temporal, DLAA pack, and Retinal filters"
    )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (AssertionError, KeyError, OSError, ValueError, json.JSONDecodeError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        sys.exit(1)
